package com.lapisserve.app.engine

import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.async
import kotlinx.coroutines.awaitAll
import kotlinx.coroutines.coroutineScope
import kotlinx.coroutines.withContext
import kotlinx.coroutines.withTimeoutOrNull
import java.io.File
import java.net.InetAddress

/**
 * The musl C library our JVM runs on reads /etc/resolv.conf, which Android doesn't have, so the JVM can't
 * resolve any hostname by itself. Android's own resolver (used here, in the app) works fine, so we resolve the
 * hostnames a Minecraft server commonly needs and hand the JVM a hosts file via -Djdk.net.hosts.file.
 */
object DnsHosts {
    /** Hosts needed by Paperclip, the Mojang auth/session services, and common plugin/update endpoints. */
    val defaultHosts = listOf(
        "piston-data.mojang.com", "piston-meta.mojang.com", "launchermeta.mojang.com", "launcher.mojang.com",
        "libraries.minecraft.net", "resources.download.minecraft.net", "textures.minecraft.net",
        "sessionserver.mojang.com", "api.mojang.com", "authserver.mojang.com", "api.minecraftservices.com",
        "discovery.minecraftservices.com", "services.minecraft.net", "minecraftservices.com", "pc.realms.minecraft.net",
        "repo.maven.apache.org", "repo1.maven.org", "maven.apache.org",
        "api.purpurmc.org", "repo.purpurmc.org", "repo.papermc.io", "fill.papermc.io", "fill-data.papermc.io", "api.papermc.io", "hangar.papermc.io", "hangarcdn.papermc.io",
        "github.com", "api.github.com", "raw.githubusercontent.com", "objects.githubusercontent.com", "release-assets.githubusercontent.com",
        "cdn.modrinth.com", "api.modrinth.com", "bstats.org", "api.spiget.org", "cdn.spiget.org",
    )

    fun parseExtra(s: String): List<String> =
        s.split(Regex("[\\s,;]+")).map { it.trim().lowercase() }.filter { it.matches(Regex("[a-z0-9.-]+")) && '.' in it }

    private suspend fun resolve(h: String, timeoutMs: Long): List<String> =
        withTimeoutOrNull(timeoutMs) {
            runCatching { InetAddress.getAllByName(h).mapNotNull { it.hostAddress?.substringBefore('%') } }.getOrNull()
        }?.distinct()?.map { "$it $h" } ?: emptyList()

    /** Resolves hosts with Android's resolver and writes them to [file]. Returns (resolved count, hosts that failed). */
    suspend fun write(file: File, extra: String): Pair<Int, List<String>> = withContext(Dispatchers.IO) {
        val hosts = (defaultHosts + parseExtra(extra)).distinct()
        // First pass is parallel; anything that timed out gets a slower, serial retry.
        val first = coroutineScope { hosts.map { h -> async { h to resolve(h, 5000) } }.awaitAll() }
        val retried = first.map { (h, r) -> if (r.isEmpty()) h to resolve(h, 10_000) else h to r }
        val lines = retried.flatMap { it.second }
        val failed = retried.filter { it.second.isEmpty() }.map { it.first }
        val out = buildString {
            appendLine("# Generated by LapisServe from Android's resolver. Do not edit.")
            appendLine("127.0.0.1 localhost")
            appendLine("::1 localhost")
            lines.forEach { appendLine(it) }
        }
        // Don't replace a good file with an empty one if the network is momentarily down.
        if (lines.isNotEmpty() || !file.exists()) file.writeText(out)
        lines.map { it.substringAfter(' ') }.distinct().size to failed
    }
}
